// Generate public JSON/TypeScript contracts from the development native binary.
import {spawnSync} from 'node:child_process';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve,dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const binary=process.env.AGENT_CAD_BUILD_BINARY??join(process.env.CARGO_TARGET_DIR??join(root,'target'),'release',process.platform==='win32'?'agent-cad.exe':'agent-cad');
function call(command){
 const p=spawnSync(binary,[command],{encoding:'utf8',maxBuffer:4*1024*1024});
 if(p.error)throw p.error;
 if(p.status!==0)throw Error(p.stderr||p.stdout);
 const r=JSON.parse(p.stdout);if(!r.ok)throw Error(JSON.stringify(r.error));return r.data;
}
const cargo=await readFile(join(root,'crates/agent-cad/Cargo.toml'),'utf8');
const version=cargo.match(/^version\s*=\s*"([^"]+)"/m)?.[1];
if(!version||call('capabilities').executor_version!==version)throw Error('development native and Cargo versions differ');
const schema=call('schema');
function type(s){
 if(s===true)return 'unknown';if(s===false)return 'never';if(s.$ref)return s.$ref.split('/').at(-1);
 if('const'in s)return JSON.stringify(s.const);if(s.enum)return s.enum.map(v=>JSON.stringify(v)).join(' | ');
 if(s.oneOf||s.anyOf){const variants=(s.oneOf??s.anyOf).map(v=>`(${type(v)})`).join(' | ');const {oneOf,anyOf,...rest}=s;return s.properties?`(${type(rest)}) & (${variants})`:variants;}
 if(s.allOf)return s.allOf.map(v=>`(${type(v)})`).join(' & ');
 if(Array.isArray(s.type))return s.type.map(v=>type({...s,type:v})).join(' | ');
 if(s.type==='null')return 'null';if(s.type==='number'||s.type==='integer')return 'number';if(s.type==='boolean')return 'boolean';if(s.type==='string')return 'string';
 if(s.type==='array'){if(s.prefixItems)return `[${s.prefixItems.map(type).join(', ')}]`;if(s.minItems===s.maxItems&&s.minItems>0&&s.minItems<=16)return `[${Array.from({length:s.minItems},()=>type(s.items)).join(', ')}]`;return `Array<${type(s.items??true)}>`;}
 if(s.type==='object'||s.properties){const fields=Object.entries(s.properties??{}).map(([k,v])=>`${JSON.stringify(k)}${s.required?.includes(k)?'':'?'}: ${type(v)}`);if(s.additionalProperties&&s.additionalProperties!==false)fields.push(`[key:string]: ${type(s.additionalProperties)}`);return fields.length?`{ ${fields.join('; ')} }`:'Record<string, unknown>';}
 throw Error(`unsupported schema fragment: ${JSON.stringify(s)}`);
}
const generated=`// Generated by scripts/schema.mjs from the Rust model contract.\n${Object.entries(schema.$defs??{}).map(([name,s])=>`export type ${name} = ${type(s)};`).join('\n')}\nexport type Model = ${type(schema)};\n`;
const query=call('query-schema');
const queryTypes=`// Generated by scripts/schema.mjs from the Rust query contract.\n${Object.entries(query.$defs??{}).map(([name,s])=>`export type ${name} = ${type(s)};`).join('\n')}\nexport type Request = ${type(query)};\n`;
for(const [name,text] of [['kernel/schemas/model.schema.json',JSON.stringify(schema,null,2)+'\n'],['kernel/src/generated.ts',generated],['kernel/schemas/query.schema.json',JSON.stringify(query,null,2)+'\n'],['kernel/src/query-generated.ts',queryTypes]]){
 const path=join(root,name);
 if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==text)throw Error(`stale generated contract: ${name}`);}
 else{await mkdir(dirname(path),{recursive:true});await writeFile(path,text);}
}
console.log(`schema and TS contract ${process.argv.includes('--check')?'verified':'generated'} for native ${version}`);
